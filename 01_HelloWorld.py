# Print
print("Hello World!") # Print message to the console

print("""
This is a multi-line string.
It can be used for comments or documentation.
""") # Print multi-line string to the console

# Variable
message_string = "Hasta la vista" # String variable, used for text (name, message, etc.)
print(message_string + " baby!") # Print message to the console with variable

message_string = "Goodbye" # Reassigning variable
print(message_string + " cruel world!")

name = 'John'
age = 30
print("My name is " + name + " and I am " + str(age) + " years old.") # Concatenating strings and variables

# Data Types
number_integer = 42 # Integer variable, used for whole numbers (age, count, etc.)
number_float = 3.14 # Float variable, used for decimal numbers (length, currency, etc.)
print("Integer: " + str(number_integer)) # Prints Integer: 42
print("Float: " + str(number_float)) # Prints Float: 3.14

# Calculations
print(573 - 74 + 1) # Prints 500
print(25 * 2)       # Prints 50
print(10 / 5)       # Prints 2.0 (division always returns a float)

coffee_price = 1.50
number_of_coffees = 4
print(coffee_price * number_of_coffees) # Prints 6.0

coffee_price = 2.00 # Updating the price 
print(coffee_price * number_of_coffees) # Prints 8.0

print(2 ** 10)  # 2 to the 10th power, or 1024
print(8 ** 2)   # 8 squared, or 64
print(9 ** 3)   # 9 * 9 * 9, 9 cubed, or 729
print(4 ** 0.5) # 4 to the half power, or 2


print(44 % 2) # Modulo by 2 returns 0 for even numbers and 1 for odd numbers. Prints 0
print(29 % 5) # Prints 4 because 29 / 5 is 5 with a remainder of 4
print(32 % 3) # Prints 2 because 32 / 3 is 10 with a remainder of 2
 

 



